"""Simulated account-level detail under each statement line, for the Review page.

Public filings stop at statement lines, so this module makes up a plausible chart of accounts under each one.
It is labeled simulated everywhere it shows. The accounts sum exactly to the filed line, and the filed amounts are
never changed. The same lines always give the same accounts: every choice is seeded from the company, the section,
and the line name with hashlib, never from a random generator. No real bank or vendor name appears in any account.

This is display data, not a deal tool: the gateway does not run it, and no deal math reads it.
"""
from __future__ import annotations

import calendar
