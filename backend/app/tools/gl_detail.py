NOTE = ("Simulated account-level detail. Public filings stop at statement lines; these accounts are generated by code "
        "and sum exactly to each filed line.")


class GLAccount(BaseModel):
    account: str
    name: str
    amount: float
    prior: float
    entries: int
    last_posted: str


@dataclass(frozen=True)
class Acct:
    """One account in a template: number, name, weight, contra (opposite sign to the line), activity (h, m, l)."""

    num: int
    name: str
    w: float
    contra: bool = False
    act: str = "m"


def A(num: int, name: str, w: float, act: str = "m") -> Acct:
    return Acct(num, name, w, False, act)


def C(num: int, name: str, w: float, act: str = "l") -> Acct:
    """A contra account. Its weight is a share of the gross of the other accounts."""
    return Acct(num, name, w, True, act)


