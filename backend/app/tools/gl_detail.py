SECTION_KEY = {"balance_sheet": "bs", "income_statement": "is", "cash_flow": "cf"}

LIABILITY_WORDS = ("payable", "liabilit", "accrued", "borrowing", "debt", "loan", "note", "deferred revenue",
                   "provision", "reserve for")
EQUITY_WORDS = ("stock", "capital", "earnings", "equity", "treasury", "comprehensive", "controlling", "reserves",
                "net investment", "dividend")
FALLBACK_SUFFIXES = [("primary", .55, "h"), ("secondary", .2, "m"), ("accruals", .12, "l"),
                     ("allocations", .08, "m"), ("adjustments", .03, "l"), ("other", .02, "m")]
ACTIVITY = {"h": (240, 2400), "m": (30, 320), "l": (1, 24)}


def _unit(*parts) -> float:
    """A number in [0, 1) seeded from the parts."""
    key = "|".join(str(p) for p in parts).encode()
    return int.from_bytes(hashlib.sha256(key).digest()[:8], "big") / 2 ** 64


def _category(line: SourceLine, past_total_assets: bool) -> int:
    """The chart-of-accounts thousand for a line no template covers."""
    name = line.line.lower()
    if line.section == "balance_sheet":
        if any(w in name for w in EQUITY_WORDS):
            return 3000
        if any(w in name for w in LIABILITY_WORDS) or past_total_assets:
            return 2000
        return 1000
    if re.search(r"revenue|sales|income$|fees earned", name) and "cost" not in name:
        return 4000
    if re.search(r"cost of|direct", name):
        return 5000
    if "tax" in name:
        return 8000
    if re.search(r"interest|other income|other expense|gain|loss|foreign|finance", name):
        return 7000
    return 6000


def _fallback(line: SourceLine, past_total_assets: bool) -> list[Acct]:
    """Generic accounts named after the line, in a block of the right thousand chosen from the line name."""
    base = _category(line, past_total_assets) + 100 * (1 + int(_unit(line.company, line.line, "block") * 9))
    label = line.line.split(":")[-1].strip() or line.line
    return [Acct(base + 10 * (i + 1), f"{label} - {suffix}", w, False, act)
            for i, (suffix, w, act) in enumerate(FALLBACK_SUFFIXES)]


def _template(line: SourceLine, past_total_assets: bool) -> list[Acct]:
    name = line.line.lower()
    key = SECTION_KEY.get(line.section, "bs")
    for pattern, sections, template in RULES:
        if key in sections.split() and re.search(pattern, name):
            return template
    return _fallback(line, past_total_assets)


SPLIT_BY_TERM = (OPERATING_LEASE, FINANCE_LEASE, FINANCING_LIABILITY, NOTES_PAYABLE, DEBT, SHORT_TERM_DEBT)


def _term(line: SourceLine, template: list[Acct]) -> str:
    """A current or long-term qualifier for the debt and lease templates, which a company often files twice."""
    if not any(template is t for t in SPLIT_BY_TERM):
        return ""
    name = line.line.lower()
    if re.search(r"long-term|non-current|net of current|less current", name):
        return " (long-term)"
    if "current" in name:
        return " (current)"
    return ""


def _decimals(amount: float) -> int:
    """The precision of the filed amount: whole units for every fixture, up to 2 places for an upload."""
    for d in range(3):
        if abs(round(amount, d) - amount) < 1e-9:
            return d
    return 2


def _split(total: int, accounts: list[Acct], seed: tuple) -> list[int]:
    """Integer amounts that sum exactly to `total`. Contra accounts take the opposite sign; the rounding remainder
    goes on the largest account."""
    weights = [a.w * (0.75 + 0.5 * _unit(*seed, a.num, "w")) for a in accounts]
    pos = sum(w for a, w in zip(accounts, weights) if not a.contra) or 1.0
    contra = sum(w for a, w in zip(accounts, weights) if a.contra)
    gross = total / (1 - min(contra, 0.9))
    raw = [(-gross * w if a.contra else gross * w / pos) for a, w in zip(accounts, weights)]
    out = [round(x) for x in raw]
    biggest = max(range(len(out)), key=lambda i: (abs(raw[i]), -i))
    out[biggest] += total - sum(out)
    return out


def _period_end(period: str) -> tuple[int, int, int]:
    """The last ISO date in the period label, or 31 December of the last year in it."""
    dates = re.findall(r"(\d{4})-(\d{2})-(\d{2})", period)
    if dates:
        y, m, d = (int(x) for x in dates[-1])
        return y, m, d
    years = re.findall(r"\b(19|20)(\d{2})\b", period)
    y = int("".join(years[-1])) if years else 2024
    return y, 12, 31


def _last_posted(line: SourceLine, acct: Acct) -> str:
    """A date in the period's end month, on or before the period end."""
    y, m, d = _period_end(line.period)
    d = min(d, calendar.monthrange(y, m)[1])
    day = d - int(_unit(line.company, line.line, acct.num, "day") * min(d, 10))
    return f"{y:04d}-{m:02d}-{max(day, 1):02d}"


def _account_count(line: SourceLine, template: list[Acct]) -> int:
    top = min(8, len(template))
    return 4 + int(_unit(line.company, line.section, line.line, "count") * (top - 3))


def detail_for(line: SourceLine, past_total_assets: bool = False) -> list[tuple[Acct, GLAccount]]:
    """The accounts under one detail line, before account numbers are made unique within the company."""
    template = _template(line, past_total_assets)
    if line.amount == 0:
        picked = template[:2]
    else:
        picked = template[:_account_count(line, template)]
    term = _term(line, template)
    dec = _decimals(line.amount)
    scale = 10 ** dec
    seed = (line.company, line.section, line.line)
    amounts = [0] * len(picked) if line.amount == 0 else _split(round(line.amount * scale), picked, seed)
    out = []
    for acct, units in zip(picked, amounts):
        amount = units / scale
        drift = (_unit(*seed, acct.num, "prior") - 0.5) * 0.44  # within +-22 percent
        prior = round(amount * (1 + drift), dec)
        lo, hi = ACTIVITY[acct.act]
        entries = 0 if units == 0 else lo + int(_unit(*seed, acct.num, "entries") * (hi - lo + 1))
        out.append((acct, GLAccount(account=str(acct.num), name=acct.name + term, amount=float(amount), prior=float(prior),
                                    entries=entries, last_posted=_last_posted(line, acct))))
    return out


def gl_detail(lines: list[SourceLine]) -> dict[str, list[GLAccount]]:
    """Simulated accounts for every detail line, keyed by source line id. Subtotals get none, since they are derived.

    Account numbers are unique within each company: a number already used goes up by one until it is free, in line
    order, so the same lines in the same order always get the same numbers."""
    used: dict[str, set[int]] = {}
    past_assets: dict[tuple[str, str], bool] = {}
    out: dict[str, list[GLAccount]] = {}
    for line in lines:
        key = (line.company, line.section)
        if line.is_total:
            if "total assets" in line.line.lower():
                past_assets[key] = True
            continue
        taken = used.setdefault(line.company, set())
        accounts = []
        for acct, gl in detail_for(line, past_assets.get(key, False)):
            num = acct.num
            while num in taken:
                num += 1
            taken.add(num)
            accounts.append(gl.model_copy(update={"account": str(num)}))
        out[line.id] = sorted(accounts, key=lambda a: a.account)
    return out


def gl_response(lines: list[SourceLine]) -> dict:
    """The body of GET /deals/{id}/gl."""
    return {"simulated": True, "note": NOTE,
            "lines": {lid: [a.model_dump() for a in accts] for lid, accts in gl_detail(lines).items()}}
